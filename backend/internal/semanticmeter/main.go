// Command semanticmeter generates the closed semantic model's resource walkers.
// Run via go generate in protocol; bootstrap builds use the reflective oracle so
// removed/renamed model fields cannot prevent regenerating stale generated code.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"reflect"
	"strconv"
	"strings"

	p "github.com/elysia-api/backend/protocol"
)

type generator struct {
	ids    map[reflect.Type]int
	types  []reflect.Type
	output bytes.Buffer
}

func (g *generator) id(t reflect.Type) int {
	if id, ok := g.ids[t]; ok {
		return id
	}
	id := len(g.types)
	g.ids[t] = id
	g.types = append(g.types, t)
	return id
}
func local(t reflect.Type) string                    { return strings.ReplaceAll(t.String(), "protocol.", "") }
func (g *generator) line(format string, args ...any) { fmt.Fprintf(&g.output, format+"\n", args...) }

func main() {
	g := generator{ids: map[reflect.Type]int{}}
	roots := []reflect.Type{reflect.TypeFor[p.Request](), reflect.TypeFor[p.Response](), reflect.TypeFor[*p.Request](), reflect.TypeFor[*p.Response](), reflect.TypeFor[[]p.Event](), reflect.TypeFor[p.Event](), reflect.TypeFor[*p.Event](), reflect.TypeFor[*p.Node]()}
	g.line("// Code generated by internal/semanticmeter; DO NOT EDIT.")
	g.line("//go:build !semanticmeter_bootstrap\n\npackage protocol\n\nimport \"strconv\"")
	g.line("func (meter *typedMeter) visitTyped(value any) (bool, bool) { switch value := value.(type) {")
	for _, t := range roots {
		g.line("case %s: return meter.measure%d(value), true", local(t), g.id(t))
	}
	g.line("default: return false, false\n} }")
	for index := 0; index < len(g.types); index++ {
		g.emit(index, g.types[index])
	}
	source, err := format.Source(g.output.Bytes())
	if err != nil {
		panic(err)
	}
	if len(os.Args) > 1 && os.Args[1] == "--check" {
		old, err := os.ReadFile("typed_meter_generated.go")
		if err != nil || !bytes.Equal(old, source) {
			panic("semantic meter is stale; run go generate ./protocol")
		}
		return
	}
	if err := os.WriteFile("typed_meter_generated.go", source, 0644); err != nil {
		panic(err)
	}
}

func (g *generator) emit(id int, t reflect.Type) {
	g.line("func (meter *typedMeter) measure%d(value %s) bool {", id, local(t))
	if t == reflect.TypeFor[p.Value]() {
		g.line("return meter.raw(value.raw)\n}")
		return
	}
	marshaler := reflect.TypeFor[interface{ MarshalJSON() ([]byte, error) }]()
	if t.Implements(marshaler) || reflect.PointerTo(t).Implements(marshaler) {
		panic("unsupported custom marshaler: " + t.String())
	}
	switch t.Kind() {
	case reflect.Pointer:
		g.line("if value == nil {return meter.scalar(4)}\nreturn meter.measure%d(*value)", g.id(t.Elem()))
	case reflect.String:
		g.line("return meter.scalar(jsonStringBytes(string(value)))")
	case reflect.Bool:
		g.line("if value {return meter.scalar(4)}\nreturn meter.scalar(5)")
	case reflect.Int, reflect.Int64:
		g.line("var buffer [20]byte\nreturn meter.scalar(len(strconv.AppendInt(buffer[:0],int64(value),10)))")
	case reflect.Slice:
		g.line("if value == nil {return meter.scalar(4)}\nif !meter.open(){return false}\nfor index := range value { if index > 0 {meter.bytes++}; if !meter.measure%d(value[index]) {return false} }\nreturn meter.close()", g.id(t.Elem()))
	case reflect.Map:
		if t.Key().Kind() != reflect.String {
			panic("unsupported map: " + t.String())
		}
		g.line("if value == nil {return meter.scalar(4)}\nif !meter.open(){return false}\ncount:=0\nfor key, child:=range value { if count>0 {meter.bytes++};count++;meter.bytes++;if !meter.scalar(jsonStringBytes(string(key))) || !meter.measure%d(child) {return false} }\nreturn meter.close()", g.id(t.Elem()))
	case reflect.Struct:
		g.line("if !meter.open(){return false}\ncount:=0")
		for i := range t.NumField() {
			f := t.Field(i)
			if !f.IsExported() {
				continue
			}
			tags := strings.Split(f.Tag.Get("json"), ",")
			if tags[0] == "-" {
				continue
			}
			if tags[0] == "" || f.Anonymous {
				panic("unsupported field: " + t.String() + "." + f.Name)
			}
			condition := "true"
			for _, tag := range tags[1:] {
				x := "value." + f.Name
				switch tag {
				case "omitzero":
					if f.Type == reflect.TypeFor[p.Value]() {
						condition = "!" + x + ".IsZero()"
					} else if f.Type.Kind() == reflect.Slice || f.Type.Kind() == reflect.Map || f.Type.Kind() == reflect.Pointer {
						condition = x + " != nil"
					} else if f.Type.Comparable() {
						condition = x + " != *new(" + local(f.Type) + ")"
					} else {
						panic("unsupported omitzero: " + f.Name)
					}
				case "omitempty":
					switch f.Type.Kind() {
					case reflect.Slice, reflect.Map, reflect.String:
						condition = "len(" + x + ") != 0"
					case reflect.Pointer:
						condition = x + " != nil"
					case reflect.Bool:
						condition = x
					case reflect.Int, reflect.Int64:
						condition = x + " != 0"
					default:
						condition = "true"
					}
				default:
					panic("unsupported tag: " + tag)
				}
			}
			// Field keys are fixed ASCII in the semantic contract. QuoteToASCII is
			// deliberately checked instead of assuming new names need no escaping.
			key := strconv.QuoteToASCII(tags[0])
			if key != `"`+tags[0]+`"` || strings.ContainsAny(tags[0], "<>&") {
				panic("non-simple JSON field name: " + tags[0])
			}
			g.line("if %s {if count>0 {meter.bytes++};count++;meter.bytes++;if !meter.scalar(%d) || !meter.measure%d(value.%s){return false}}", condition, len(key), g.id(f.Type), f.Name)
		}
		g.line("return meter.close()")
	default:
		panic("unsupported semantic field type: " + t.String())
	}
	g.line("}")
}
