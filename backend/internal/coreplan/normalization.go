package main

import (
	"reflect"

	p "github.com/elysia-api/backend/protocol"
)

func (g *generator) emitSemanticNormalizers() {
	normalizers := generator{names: g.names, types: g.types}
	normalizers.line("// Code generated by internal/coreplan; DO NOT EDIT.")
	normalizers.line("//go:build !coreplan_bootstrap\n\npackage protocol\nimport \"reflect\"")
	normalizers.line("func normalizeCoreSemantic(value reflect.Value,cache *semanticCache){switch selected:=value.Interface().(type){")
	for _, kind := range normalizers.types {
		switch kind.Kind() {
		case reflect.Pointer:
			normalizers.line("case %s:", local(kind))
			if needsSemanticNormalization(kind.Elem()) {
				normalizers.line("if selected!=nil {normalizeCore%s(selected,cache)}", normalizers.name(kind.Elem()))
			}
			normalizers.line("return")
		case reflect.Slice:
			normalizers.line("case %s:", local(kind))
			if needsSemanticNormalization(kind) {
				normalizers.line("normalizeCore%s(&selected,cache)", normalizers.name(kind))
			}
			normalizers.line("return")
		}
	}
	normalizers.line("};switch selected:=value.Addr().Interface().(type){")
	for _, kind := range normalizers.types {
		if kind.Kind() == reflect.Pointer || kind.Kind() == reflect.Slice {
			continue
		}
		normalizers.line("case *%s:", local(kind))
		if needsSemanticNormalization(kind) {
			normalizers.line("normalizeCore%s(selected,cache)", normalizers.name(kind))
		}
		normalizers.line("return")
	}
	normalizers.line("default:panic(\"unsupported semantic normalization type\")}}")
	for index := 0; index < len(normalizers.types); index++ {
		kind := normalizers.types[index]
		if needsSemanticNormalization(kind) {
			normalizers.emitNormalize(normalizers.name(kind), kind)
		}
	}
	normalizers.writeSource("semantic_normalize_generated.go")
}

func (g *generator) emitNormalize(name string, kind reflect.Type) {
	g.line("func normalizeCore%s(value *%s,cache *semanticCache){", name, local(kind))
	if kind == reflect.TypeFor[p.Value]() {
		g.line("if !value.IsZero(){*value=cache.normalize(*value)}\n}")
		return
	}
	switch kind.Kind() {
	case reflect.Struct:
		for _, field := range fields(kind) {
			if !needsSemanticNormalization(field.typeOf) {
				continue
			}
			if field.condition != "" {
				g.line("if %s {normalizeCore%s(&value.%s,cache)} else {value.%s=*new(%s)}", field.condition, g.name(field.typeOf), field.name, field.name, local(field.typeOf))
			} else {
				g.line("normalizeCore%s(&value.%s,cache)", g.name(field.typeOf), field.name)
			}
		}
	case reflect.Pointer:
		g.line("if *value!=nil{normalizeCore%s(*value,cache)}", g.name(kind.Elem()))
	case reflect.Slice:
		if needsSemanticNormalization(kind.Elem()) {
			g.line("for index:=range *value {normalizeCore%s(&(*value)[index],cache)}", g.name(kind.Elem()))
		}
	case reflect.Map:
		g.line("*value=normalizeSemanticKeys(*value)")
		if kind == reflect.TypeFor[p.Object]() {
			g.line("cache.normalizeObject(*value)")
		} else if needsSemanticNormalization(kind.Elem()) {
			g.line("for key,child:=range *value{normalizeCore%s(&child,cache);(*value)[key]=child}", g.name(kind.Elem()))
		}
	case reflect.String:
		g.line("*value=%s(normalizeSemanticString(string(*value)))", local(kind))
	default:
		panic("unnecessary semantic normalizer: " + kind.String())
	}
	g.line("}")
}

func needsSemanticNormalization(kind reflect.Type) bool {
	if kind == reflect.TypeFor[p.Value]() {
		return true
	}
	switch kind.Kind() {
	case reflect.Pointer:
		return needsSemanticNormalization(kind.Elem())
	case reflect.String, reflect.Struct, reflect.Map, reflect.Slice:
		return true
	}
	return false
}
