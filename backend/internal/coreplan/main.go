// Command coreplan generates direct access to the closed semantic model.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"reflect"
	"strconv"
	"strings"

	p "github.com/elysia-api/backend/protocol"
)

type generator struct {
	names  map[reflect.Type]string
	types  []reflect.Type
	output bytes.Buffer
}

func (g *generator) name(t reflect.Type) string {
	if name, ok := g.names[t]; ok {
		return name
	}
	name := typeName(t)
	for previous, used := range g.names {
		if used == name {
			panic("conflicting generated type names: " + previous.String() + " and " + t.String())
		}
	}
	g.names[t] = name
	g.types = append(g.types, t)
	return name
}

func typeName(t reflect.Type) string {
	if name := t.Name(); name != "" {
		return strings.ToUpper(name[:1]) + name[1:]
	}
	switch t.Kind() {
	case reflect.Pointer:
		return typeName(t.Elem()) + "Pointer"
	case reflect.Slice:
		return typeName(t.Elem()) + "Slice"
	case reflect.Map:
		return typeName(t.Elem()) + "Map"
	}
	panic("unsupported anonymous core type: " + t.String())
}

func local(t reflect.Type) string                    { return strings.ReplaceAll(t.String(), "protocol.", "") }
func (g *generator) line(format string, args ...any) { fmt.Fprintf(&g.output, format+"\n", args...) }

func main() {
	g := generator{names: map[reflect.Type]string{}}
	g.line("// Code generated by internal/coreplan; DO NOT EDIT.")
	g.line("//go:build !coreplan_bootstrap\n\npackage protocol")
	for _, entry := range []struct {
		name   string
		typeOf reflect.Type
	}{{"Request", reflect.TypeFor[p.Request]()}, {"Response", reflect.TypeFor[p.Response]()}, {"Event", reflect.TypeFor[p.Event]()}} {
		g.line("func decodeCore%sOutput(output JSONOutput) (*%s,error) { return decodeCoreOutput(output, writeCore%s) }", entry.name, local(entry.typeOf), g.name(entry.typeOf))
		g.line("func decodeCore%sOutputWithin(output JSONOutput,reader *valueReader) (*%s,error) { return decodeCoreOutputWithin(output, writeCore%s,reader) }", entry.name, local(entry.typeOf), g.name(entry.typeOf))
		g.line("func readCore%sOutput(value *%s,pointer []string,cache *semanticCache) (JSONOutput,error) {return readCore%s(value,pointer,cache)}", entry.name, local(entry.typeOf), g.name(reflect.PointerTo(entry.typeOf)))
	}
	g.line("func decodeCoreEventsOutput(output JSONOutput) ([]Event,error) { value,err:=decodeCoreOutput(output,writeCore%s);if err!=nil{return nil,err};return *value,nil }", g.name(reflect.TypeFor[[]p.Event]()))
	g.line("func readCoreEventsOutput(value []Event,pointer []string,cache *semanticCache) (JSONOutput,error) {return readCore%s(value,pointer,cache)}", g.name(reflect.TypeFor[[]p.Event]()))
	for index := 0; index < len(g.types); index++ {
		g.emitWriter(g.name(g.types[index]), g.types[index])
		g.emitReader(g.name(g.types[index]), g.types[index])
	}
	g.emitRequestFieldReader()
	objectTypes := collectRequestObjectTypes()
	for _, kind := range g.types {
		if objectTypes[kind] {
			g.emitObjectSelector(g.name(kind), kind, objectTypes)
		}
	}
	source, err := format.Source(g.output.Bytes())
	if err != nil {
		panic(err)
	}
	const path = "plan_core_generated.go"
	if len(os.Args) > 1 && os.Args[1] == "--check" {
		old, err := os.ReadFile(path)
		if err != nil || !bytes.Equal(old, source) {
			panic("core plan accessors are stale; run go generate ./protocol")
		}
		return
	}
	if err := os.WriteFile(path, source, 0644); err != nil {
		panic(err)
	}
}

// Fixed request fields resolve once when a plan compiles. Dynamic map keys and
// indexes retain the normal generated reader and its error/omission rules.
func (g *generator) emitRequestFieldReader() {
	requestFields := fields(reflect.TypeFor[p.Request]())
	g.line("func coreRequestFieldIndex(key string) uint8 {switch key {")
	for index, field := range requestFields {
		g.line("case %q:return %d", field.key, index+1)
	}
	g.line("};return 0}")
	g.line("func readCoreRequestField(value *Request,field uint8,pointer []string,cache *semanticCache)(JSONOutput,error){switch field {")
	for index, field := range requestFields {
		g.line("case %d:", index+1)
		if field.condition != "" {
			g.line("if %s {return readCore%s(value.%s,pointer,cache)};return JSONOutput{},nil", field.condition, g.name(field.typeOf), field.name)
		} else {
			g.line("return readCore%s(value.%s,pointer,cache)", g.name(field.typeOf), field.name)
		}
	}
	g.line("};panic(\"uncompiled request field\")}")
}

type field struct {
	name, key string
	typeOf    reflect.Type
	condition string
}

func fields(t reflect.Type) []field {
	var result []field
	for index := 0; index < t.NumField(); index++ {
		value := t.Field(index)
		if !value.IsExported() {
			continue
		}
		tags := strings.Split(value.Tag.Get("json"), ",")
		if tags[0] == "-" {
			continue
		}
		if value.Anonymous || tags[0] == "" {
			panic("unsupported field: " + t.String() + "." + value.Name)
		}
		condition := ""
		selected := "value." + value.Name
		for _, tag := range tags[1:] {
			switch tag {
			case "omitzero":
				if value.Type == reflect.TypeFor[p.Value]() {
					condition = "!" + selected + ".IsZero()"
				} else if value.Type.Kind() == reflect.Slice || value.Type.Kind() == reflect.Map || value.Type.Kind() == reflect.Pointer {
					condition = selected + "!=nil"
				} else if value.Type.Comparable() {
					condition = selected + "!=*new(" + local(value.Type) + ")"
				} else {
					panic("unsupported omitzero: " + value.Name)
				}
			case "omitempty":
				switch value.Type.Kind() {
				case reflect.Slice, reflect.Map, reflect.String:
					condition = "len(" + selected + ")!=0"
				case reflect.Pointer:
					condition = selected + "!=nil"
				case reflect.Bool:
					condition = selected
				case reflect.Int, reflect.Int64:
					condition = selected + "!=0"
				}
			default:
				panic("unsupported JSON tag: " + tag)
			}
		}
		result = append(result, field{value.Name, tags[0], value.Type, condition})
	}
	return result
}

func (g *generator) emitWriter(name string, t reflect.Type) {
	g.line("func writeCore%s(output JSONOutput,value *%s,reader *valueReader) error {", name, local(t))
	if t == reflect.TypeFor[p.Value]() {
		g.line("return assignCoreValue(output,value,reader)\n}")
		return
	}
	switch t.Kind() {
	case reflect.Pointer:
		g.line("if coreOutputIsNull(output){*value=nil;return nil};if *value==nil{*value=new(%s)};return writeCore%s(output,*value,reader)", local(t.Elem()), g.name(t.Elem()))
	case reflect.String, reflect.Bool, reflect.Int, reflect.Int64:
		g.line("return writeCoreScalar(output,value)")
	case reflect.Slice:
		g.line("if coreOutputIsNull(output){*value=nil;return nil};reader=coreOutputReader(output,reader);items,err:=coreArrayItems(output);if err!=nil{return err};*value=make(%s,len(items));for index,item:=range items {if err:=writeCore%s(item,&(*value)[index],reader);err!=nil{return err}};return nil", local(t), g.name(t.Elem()))
	case reflect.Map:
		if t.Key().Kind() != reflect.String {
			panic("unsupported map: " + t.String())
		}
		g.line("if coreOutputIsNull(output){*value=nil;return nil};reader=coreOutputReader(output,reader);fields,err:=coreObjectFields(output);if err!=nil{return err};if *value==nil{*value=make(%s,len(fields))};for _,field:=range fields {key:=ownCoreMapKey(field.key);child:=(*value)[key];if err:=writeCore%s(field.value,&child,reader);err!=nil{return err};(*value)[key]=child};return nil", local(t), g.name(t.Elem()))
	case reflect.Struct:
		if t == reflect.TypeFor[p.Native]() || t == reflect.TypeFor[p.Provenance]() {
			origin := "capturedNativeOrigin"
			if t == reflect.TypeFor[p.Provenance]() {
				origin = "capturedProvenanceOrigin"
			}
			g.line("if !coreOutputIsNull(output){if err:=requireCoreOrigin(output,reader,%s);err!=nil{return err}}", origin)
		}
		g.line("if coreOutputIsNull(output){return nil};reader=coreOutputReader(output,reader);fields,err:=coreObjectFields(output);if err!=nil{return err};for _,field:=range fields {if err:=writeCore%sField(field,value,reader);err!=nil{return err}};return nil\n}", name)
		g.line("func writeCore%sField(field jsonOutputField,value *%s,reader *valueReader) error {switch field.key {", name, local(t))
		var names []string
		for _, field := range fields(t) {
			names = append(names, strconv.Quote(field.key))
			g.line("case %q:return writeCore%s(field.value,&value.%s,reader)", field.key, g.name(field.typeOf), field.name)
		}
		g.line("default: key:=foldedCoreField(field.key,[]string{%s});if key==\"\"{return unknownCoreField(field.key)};field.key=key;return writeCore%sField(field,value,reader)\n}", strings.Join(names, ","), name)
	default:
		panic("unsupported core type: " + t.String())
	}
	g.line("}")
}

func (g *generator) emitReader(name string, t reflect.Type) {
	g.line("func readCore%s(value %s,pointer []string,cache *semanticCache)(JSONOutput,error){", name, local(t))
	if t == reflect.TypeFor[p.Value]() {
		g.line("return readCoreLeaf(value,pointer,cache)\n}")
		return
	}
	switch t.Kind() {
	case reflect.Pointer:
		g.line("if value==nil{return readCoreScalar(Value{raw:\"null\"},pointer)};return readCore%s(*value,pointer,cache)", g.name(t.Elem()))
	case reflect.String:
		g.line("return readCoreScalar(StringValue(string(value)),pointer)")
	case reflect.Bool:
		g.line("return readCoreScalar(coreBoolean(bool(value)),pointer)")
	case reflect.Int, reflect.Int64:
		g.line("return readCoreScalar(coreInteger(int64(value)),pointer)")
	case reflect.Slice:
		g.line("if value==nil{return readCoreScalar(Value{raw:\"null\"},pointer)};if len(pointer)!=0 {index,err:=coreArrayIndex(pointer[0],len(value));if err!=nil||index<0{return JSONOutput{},err};return readCore%s(value[index],pointer[1:],cache)};items:=make([]JSONOutput,len(value));for index,child:=range value {output,err:=readCore%s(child,nil,cache);if err!=nil{return JSONOutput{},err};items[index]=output};return finishCoreOutput(&jsonOutputNode{items:items}),nil", g.name(t.Elem()), g.name(t.Elem()))
	case reflect.Map:
		g.line("if value==nil{return readCoreScalar(Value{raw:\"null\"},pointer)};if len(pointer)!=0 {key,ok:=coreMapKey(value,pointer[0]);if !ok{return JSONOutput{},nil};return readCore%s(value[key],pointer[1:],cache)};fields:=make([]jsonOutputField,0,len(value));for _,key:=range sortedKeys(value) {output,err:=readCore%s(value[key],nil,cache);if err!=nil{return JSONOutput{},err};fields=append(fields,jsonOutputField{key,output})};return finishCoreOutput(&jsonOutputNode{object:true,fields:fields}),nil", g.name(t.Elem()), g.name(t.Elem()))
	case reflect.Struct:
		g.line("if len(pointer)!=0 {switch pointer[0] {")
		for _, field := range fields(t) {
			if field.condition == "" {
				g.line("case %q:return readCore%s(value.%s,pointer[1:],cache)", field.key, g.name(field.typeOf), field.name)
			} else {
				g.line("case %q:if %s {return readCore%s(value.%s,pointer[1:],cache)};return JSONOutput{},nil", field.key, field.condition, g.name(field.typeOf), field.name)
			}
		}
		g.line("default:return JSONOutput{},nil\n}};fields:=make([]jsonOutputField,0,%d)", len(fields(t)))
		if len(fields(t)) != 0 {
			g.line("var output JSONOutput;var err error")
		}
		for _, field := range fields(t) {
			if field.condition != "" {
				g.line("if %s {", field.condition)
			}
			g.line("output,err=readCore%s(value.%s,nil,cache);if err!=nil{return JSONOutput{},err};fields=append(fields,jsonOutputField{%q,output})", g.name(field.typeOf), field.name, field.key)
			if field.condition != "" {
				g.line("}")
			}
		}
		g.line("return finishCoreOutput(&jsonOutputNode{object:true,hasCanonicalKeys:true,fields:fields}),nil")
	default:
		panic("unsupported core type: " + t.String())
	}
	g.line("}")
}

// Object selectors stop at opaque Values. Their field conditions come from the
// same tags as readers so selecting keys cannot resurrect omitted containers.
func collectRequestObjectTypes() map[reflect.Type]bool {
	object := reflect.TypeFor[p.Object]()
	reachable := map[reflect.Type]bool{}
	var visit func(reflect.Type)
	visit = func(kind reflect.Type) {
		if reachable[kind] || kind == reflect.TypeFor[p.Value]() {
			return
		}
		reachable[kind] = true
		switch kind.Kind() {
		case reflect.Pointer, reflect.Slice:
			visit(kind.Elem())
		case reflect.Struct:
			for _, field := range fields(kind) {
				visit(field.typeOf)
			}
		}
	}
	visit(reflect.TypeFor[*p.Request]())
	selected := map[reflect.Type]bool{object: true}
	for hasChanges := true; hasChanges; {
		hasChanges = false
		for kind := range reachable {
			if selected[kind] {
				continue
			}
			canSelect := false
			switch kind.Kind() {
			case reflect.Pointer, reflect.Slice:
				canSelect = selected[kind.Elem()]
			case reflect.Struct:
				for _, field := range fields(kind) {
					canSelect = canSelect || selected[field.typeOf]
				}
			}
			if canSelect {
				selected[kind], hasChanges = true, true
			}
		}
	}
	return selected
}

func (g *generator) emitObjectSelector(name string, kind reflect.Type, selected map[reflect.Type]bool) {
	g.line("func isCore%sObjectPath(pointer []string) bool {", name)
	switch kind.Kind() {
	case reflect.Pointer:
		g.line("return isCore%sObjectPath(pointer)", g.name(kind.Elem()))
	case reflect.Map:
		g.line("return len(pointer)==0")
	case reflect.Slice:
		g.line("if len(pointer)==0{return false};_,err:=coreArrayIndex(pointer[0],0);return err==nil&&isCore%sObjectPath(pointer[1:])", g.name(kind.Elem()))
	case reflect.Struct:
		g.line("if len(pointer)==0{return false};switch pointer[0]{")
		for _, field := range fields(kind) {
			if selected[field.typeOf] {
				g.line("case %q:return isCore%sObjectPath(pointer[1:])", field.key, g.name(field.typeOf))
			}
		}
		g.line("default:return false}")
	}
	g.line("}")
	g.line("func selectCore%sObject(value %s,pointer []string)(Object,bool,error){", name, local(kind))
	switch kind.Kind() {
	case reflect.Pointer:
		g.line("if value==nil{return selectNullCoreObject(pointer)};return selectCore%sObject(*value,pointer)", g.name(kind.Elem()))
	case reflect.Map:
		g.line("return value,true,nil")
	case reflect.Slice:
		g.line("if value==nil{return selectNullCoreObject(pointer)};index,err:=coreArrayIndex(pointer[0],len(value));if err!=nil||index<0{return nil,false,err};return selectCore%sObject(value[index],pointer[1:])", g.name(kind.Elem()))
	case reflect.Struct:
		g.line("switch pointer[0]{")
		for _, field := range fields(kind) {
			if !selected[field.typeOf] {
				continue
			}
			if field.condition == "" {
				g.line("case %q:return selectCore%sObject(value.%s,pointer[1:])", field.key, g.name(field.typeOf), field.name)
			} else {
				g.line("case %q:if %s{return selectCore%sObject(value.%s,pointer[1:])};return nil,false,nil", field.key, field.condition, g.name(field.typeOf), field.name)
			}
		}
		g.line("default:return nil,false,nil}")
	}
	g.line("}")
}
