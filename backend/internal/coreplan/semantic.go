package main

import (
	"reflect"

	p "github.com/elysia-api/backend/protocol"
)

func (g *generator) emitSemanticClones() {
	clones := generator{names: g.names, types: g.types}
	clones.line("// Code generated by internal/coreplan; DO NOT EDIT.")
	clones.line("//go:build !coreplan_bootstrap\n\npackage protocol\nimport \"reflect\"")
	clones.line("func cloneCoreSemantic(input any) reflect.Value {switch value:=input.(type) {")
	for _, kind := range []reflect.Type{
		reflect.TypeFor[p.Request](), reflect.TypeFor[*p.Request](),
		reflect.TypeFor[p.Response](), reflect.TypeFor[*p.Response](),
		reflect.TypeFor[p.Event](), reflect.TypeFor[*p.Event](),
		reflect.TypeFor[[]p.Event](), reflect.TypeFor[*p.Node](),
	} {
		clones.line("case %s: result:=cloneCore%s(value)", local(kind), clones.name(kind))
		if kind.Kind() == reflect.Struct {
			// The existing normalization boundary needs addressable value roots.
			clones.line("return reflect.ValueOf(&result).Elem()")
		} else {
			clones.line("return reflect.ValueOf(result)")
		}
	}
	clones.line("default:panic(\"unsupported semantic clone root\")}}")
	for index := 0; index < len(clones.types); index++ {
		kind := clones.types[index]
		if hasMutableSemantic(kind) {
			clones.emitClone(clones.name(kind), kind)
		}
	}
	clones.writeSource("semantic_clone_generated.go")
}

// Serialization and ownership share the closed model's exported field catalogue.
// Whole struct assignment retains private host receipts without traversing them.
func (g *generator) emitClone(name string, kind reflect.Type) {
	g.line("func cloneCore%s(value %s) %s {", name, local(kind), local(kind))
	switch kind.Kind() {
	case reflect.Struct:
		g.line("result:=value")
		for _, field := range fields(kind) {
			if hasMutableSemantic(field.typeOf) {
				g.line("result.%s=cloneCore%s(value.%s)", field.name, g.name(field.typeOf), field.name)
			}
		}
		g.line("return result")
	case reflect.Pointer:
		g.line("if value==nil{return nil}")
		if hasMutableSemantic(kind.Elem()) {
			g.line("result:=cloneCore%s(*value)", g.name(kind.Elem()))
		} else {
			g.line("result:=*value")
		}
		g.line("return &result")
	case reflect.Slice:
		g.line("if value==nil{return nil};result:=make(%s,len(value))", local(kind))
		if hasMutableSemantic(kind.Elem()) {
			g.line("for index,child:=range value {result[index]=cloneCore%s(child)}", g.name(kind.Elem()))
		} else {
			g.line("copy(result,value)")
		}
		g.line("return result")
	case reflect.Map:
		g.line("if value==nil{return nil};result:=make(%s,len(value));for key,child:=range value {", local(kind))
		if hasMutableSemantic(kind.Elem()) {
			g.line("result[key]=cloneCore%s(child)", g.name(kind.Elem()))
		} else {
			g.line("result[key]=child")
		}
		g.line("};return result")
	default:
		panic("immutable clone function: " + kind.String())
	}
	g.line("}")
}

func hasMutableSemantic(kind reflect.Type) bool {
	if kind == reflect.TypeFor[p.Value]() {
		return false
	}
	switch kind.Kind() {
	case reflect.Pointer, reflect.Slice, reflect.Map:
		return true
	case reflect.Struct:
		for _, field := range fields(kind) {
			if hasMutableSemantic(field.typeOf) {
				return true
			}
		}
	}
	return false
}
